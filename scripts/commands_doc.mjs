// Writes docs/COMMANDS.md from the slash-command registry, so the reference always matches the code.
//   node scripts/commands_doc.mjs
import { writeFileSync } from 'node:fs';
import { all } from '../keystone_worklog/static/commands/registry.js';
import { HIGH, LOW } from '../keystone_worklog/static/commands/router.js';

const groups = new Map();
for (const c of all(null)) (groups.get(c.group) || groups.set(c.group, []).get(c.group)).push(c);
const esc = s => String(s).replace(/\|/g, '\\|');

const out = [`# Slash commands

Keystone's everyday actions without an AI model. Type \`/\` in the assistant box, in the command palette (Ctrl+K) or in
quick capture (Ctrl+Shift+Space). Changes use the same previews, Undo and git commits as the assistant; \`/help\` and
\`/help <command>\` show this list in the app.

<!-- Generated by scripts/commands_doc.mjs from keystone_worklog/static/commands/registry.js – edit those, not this file. -->

## How to write them

| What | Forms |
|---|---|
| Dates | \`today\`, \`yesterday\`, \`tomorrow\`, \`mon\`…\`sun\`, \`last fri\`, \`next mon\`, \`+3d\`, \`-2d\`, \`+1w\`, \`2026-11-03\`, \`11/3\`, \`nov 3\`. \`/log mon\` means the last Monday; \`due:mon\` the next one. |
| Ranges | \`mon..fri\`, \`nov 17..nov 28\`, \`this week\`, \`last week\`, \`this period\`, \`last period\` |
| Hours | \`2h\`, \`1.5h\`, \`90m\`, \`2:30\`, \`2h30\` |
| Projects | \`#bridge\` (any part of the name, or the network number); \`#"Girder Bridge rehab"\` for an exact name |
| People | \`@Maria\`, \`@"Sam Lee"\`, \`@Maria[50%]\` |
| Notes | \`[[Note name]]\`, \`"Note name"\`, \`today\` (Today.md), \`this\` (the open note) |
| Settings of a command | \`key:value\`, e.g. \`due:fri\`, \`status:doing\`, \`in:Projects\`, \`plan:girder\`, \`title:"New title"\` |
| Text after a target | \`/append <note> :: <text>\` |

When a name matches more than one thing (\`#bridge\` with two bridge projects), nothing is guessed: you get a button
for each, and the line under the box says what is wrong before you press Enter.

## Several at once

- **Lists:** \`/log 2h #girder, 1.5h #cr12, 0.5h #admin yesterday\` – a date at the end applies to every part.
- **Ranges:** \`/log 8h #girder mon..fri\` logs each scheduled working day (add \`all\` for days off too).
- **Chains:** separate commands with \`;\`, a new line or \`then\`. Everything is checked first, you approve once,
  they run in order and stop at the first problem; **Undo all** reverses them.
- **Bulk:** \`/cards overdue -> due:+7d\`, \`/fus today -> due:tomorrow\`, \`/todos overdue -> done\`, \`/tasks late -> +2d\`.
  Every item is listed with a tick box first, whatever the confirmation setting.
- **Pipes:** \`/find bearing | append today\`, \`/actions this | todo\`, \`/grep TBD in:Projects | move Projects/Open\`.
- **\`$\`** is what the previous command made: \`/new "Pad memo" tpl:Memo ; /append $ :: Started\`.
- **Routines:** saved lists of commands (Settings → Slash commands), run with \`/name\` or from the Today page.
  \`{1}\` is the first word after the routine's name, \`{1|usual}\` has a default, and a line starting with \`?\` is
  skipped when it doesn't apply. The defaults are \`/start\` (carry yesterday's todos, brief me), \`/eod\` (fill the day,
  show today) and \`/monday\` (last week's status note, cards due, overdue replies).

## Plain text

Without a slash, Keystone first tries rules (\`log 2h to girder yesterday\` → \`/log 2h #girder yesterday\`). With no
assistant model it then compares the text with example sentences using the in-browser embedding model and offers
the closest commands (it suggests at ${HIGH} similarity or more, offers choices from ${LOW}). Only a rule match runs anything
by itself, and only a look-up; changes always wait for a click. With a model, text that no rule matches goes to the
model. \`/why <text>\` shows how a sentence is understood.
`];

for (const [g, cs] of groups) {
  out.push(`## ${g}\n\n| Command | What it does | Examples |\n|---|---|---|`);
  for (const c of cs) out.push(`| \`${esc(c.sig)}\` | ${esc(c.help)}${c.aliases && c.aliases.length ? ` Also ${c.aliases.map(a => '`/' + a + '`').join(', ')}.` : ''}${c.accepts ? ' Takes a list from a pipe.' : ''} | ${c.examples.map(e => '`' + esc(e) + '`').join('<br>')} |`);
  out.push('');
}
writeFileSync(new URL('../docs/COMMANDS.md', import.meta.url), out.join('\n'));
console.log(`docs/COMMANDS.md: ${all(null).length} commands`);
