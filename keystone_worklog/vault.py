"""Obsidian vault export + deliverable sync for Keystone.

The tracker (data/data.json) stays the source of truth. Each generated note has a
block between START/END markers that is rewritten on every save; anything outside
it belongs to the user. The one thing that flows back from the vault is deliverable
checkboxes (and new "- [ ]" lines) under "### Deliverables" in a project note.
"""
import json
import os
import random
import re
import string
import time
from datetime import date, timedelta
from pathlib import Path

from . import fsutil

DEFAULT_FOLDER = "Keystone"  # tracker sub-folder in the vault (configurable in Settings)
START = "<!-- nwa-tracker:start -->"  # marker names kept for compatibility with existing vaults
END = "<!-- nwa-tracker:end -->"
NOTICE = ("%% Generated by Keystone. This block is rewritten on every save. You can tick deliverables "
          "or add new '- [ ] task' lines under Deliverables; write your own notes outside this block. %%")
REGION = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
TASK = re.compile(r"^\s*[-*+] \[([ xX])\] (.*?)\s*$")
BLOCK_ID = re.compile(r"\s*\^dl-([A-Za-z0-9]+)$")
DUE = re.compile(r"\s*📅\s*(\d{4}-\d{2}-\d{2})")

STAGES = [("todo", "To do"), ("doing", "In progress"), ("blocked", "Blocked"), ("done", "Done")]
STAGE_LABEL = dict(STAGES)
DAYS = 7
PERIOD_LEN = 14


# ---------- small helpers ----------
def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def r2(x):
    return f"{round(x, 2):g}"


def d(s):
    return date.fromisoformat(s)


def short(s):
    x = d(s)
    return f"{x.strftime('%b')} {x.day}"


def cell(v):
    return str(v).replace("|", "\\|").replace("\n", " ")


def safe_name(s, fallback="Untitled"):
    s = re.sub(r'[\\/:*?"<>|#^\[\]]', "-", s or "").strip(" .")
    return (s[:80].strip() or fallback)


def safe_folder(s):
    parts = [safe_name(p, "") for p in re.split(r"[\\/]+", s or "")]
    parts = [p for p in parts if p and p not in (".", "..") and not p.startswith(".")]
    return Path(*parts) if parts else Path(DEFAULT_FOLDER)


def new_id():
    return "".join(random.choices(string.ascii_lowercase + string.digits, k=7))


def project_label(p):
    return (p.get("name") or "").strip() or f"{p.get('network', '')} / {p.get('activity', '')}"


def write_if_changed(path, text):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == text:
        return False
    fsutil.write_text(path, text)
    return True


def write_region(path, body, tail="## Notes\n\n"):
    """Replace the generated block in `path`, keeping everything outside it."""
    block = f"{START}\n{NOTICE}\n\n{body.rstrip()}\n{END}"
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old is None:
        new = f"{block}\n\n{tail}"
    elif REGION.search(old):
        new = REGION.sub(lambda _: block, old, count=1)
    else:
        new = f"{block}\n\n{old}"
    return write_if_changed(path, new)


def read_region(path):
    if not path.exists():
        return None
    m = REGION.search(path.read_text(encoding="utf-8"))
    return m.group(0) if m else None


# ---------- numbers (mirrors the web app) ----------
def row_total(r):
    return sum(num(v) for v in r.get("h", []))


def period_total(p):
    return sum(row_total(r) for w in p.get("weeks", []) for r in w.get("rows", []))


def key(r):
    return f"{(r.get('network') or '').strip()}|{(r.get('activity') or '').strip()}"


def leave_info(s, periods, typ, start):
    k = (d(start) - d(s["leaveStart"])).days // PERIOD_LEN
    if k < 0:
        return None
    code = {"sick": "LS", "annual": "LA"}[typ]
    used = sum(row_total(r) for ps, p in periods.items() if s["leaveStart"] <= ps <= start
               for w in p.get("weeks", []) for r in w.get("rows", []) if r.get("code") == code)
    accrued = num(s.get(typ + "Start")) + num(s.get(typ + "Rate")) * (k + 1)
    return {"used": used, "balance": accrued - used}


def current_start(s):
    anchor = d(s["anchor"])
    k = (date.today() - anchor).days // PERIOD_LEN
    return (anchor + timedelta(days=k * PERIOD_LEN)).isoformat()


# ---------- manifest ----------
def load_manifest(path, folder):
    try:
        m = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        m = {}
    if m.get("folder") != str(folder):
        m = {"folder": str(folder), "projects": {}, "ticks": {}}
    m.setdefault("projects", {})
    m.setdefault("ticks", {})
    return m


def target(data):
    s = data.get("settings", {})
    root = Path(s["vaultPath"]).expanduser().resolve()
    return root, root / safe_folder(s.get("vaultFolder"))


# ---------- sync: vault -> app ----------
def sync(data, man, root):
    """Apply deliverable ticks / new task lines made in the vault. Returns number of changes."""
    changes = 0
    dels = data.setdefault("deliverables", [])
    by_id = {x["id"]: x for x in dels}
    for p in data.get("projects", []):
        rel = man["projects"].get(p.get("id"))
        region = rel and read_region(root / rel)
        if not region:
            continue
        in_dl = False
        for line in region.splitlines():
            if line.startswith("### "):
                in_dl = line.strip() == "### Deliverables"
                continue
            m = in_dl and TASK.match(line)
            if not m:
                continue
            checked, text = m.group(1) != " ", m.group(2)
            idm = BLOCK_ID.search(text)
            if idm:
                dl = by_id.get(idm.group(1))
                prev = man["ticks"].get(idm.group(1))
                if dl and prev is not None and checked != prev:
                    dl["status"] = "done" if checked else ("todo" if dl.get("status") == "done" else dl.get("status"))
                    changes += 1
            else:  # a task typed in Obsidian -> new deliverable on the board
                due = DUE.search(text)
                title = DUE.sub("", text)
                title = re.sub(r"\s·\s(" + "|".join(STAGE_LABEL.values()) + r")\b", "", title).strip(" ·")
                if title:
                    nd = {"id": new_id(), "title": title, "projectId": p["id"], "status": "done" if checked else "todo",
                          "due": due.group(1) if due else "", "notes": ""}
                    dels.append(nd)
                    by_id[nd["id"]] = nd
                    changes += 1
    return changes


# ---------- export: app -> vault ----------
def export(data, man, root, folder):
    s = data.get("settings", {})
    periods = {k: v for k, v in sorted(data.get("periods", {}).items())}
    projects = data.get("projects", [])
    dels = data.get("deliverables", [])
    written = 0

    # project note paths (stable per project id; renamed when the project is renamed)
    files, claimed = {}, set()
    for p in projects:
        if not ((p.get("network") or "").strip() or (p.get("activity") or "").strip()):
            continue
        name = safe_name(project_label(p))
        want = folder / "Projects" / f"{name}.md"
        if str(want).lower() in claimed:
            want = folder / "Projects" / f"{name} ({safe_name(p.get('network'))}-{safe_name(p.get('activity'))}).md"
        claimed.add(str(want).lower())
        old = man["projects"].get(p["id"])
        if old and (root / old) != want and (root / old).exists() and not want.exists():
            want.parent.mkdir(parents=True, exist_ok=True)
            os.replace(root / old, want)
        files[p["id"]] = want
    link = {pid: f.stem for pid, f in files.items()}
    by_key = {key(p): p for p in projects}

    # hours per project per period (RG only)
    used, per_period = {}, {}
    for ps, per in periods.items():
        for w in per.get("weeks", []):
            for r in w.get("rows", []):
                if r.get("code", "RG") != "RG":
                    continue
                t = row_total(r)
                used[key(r)] = used.get(key(r), 0) + t
                if t:
                    per_period.setdefault(key(r), {}).setdefault(ps, 0)
                    per_period[key(r)][ps] += t

    def ts_name(ps):
        return f"Timesheet {ps}"

    def period_title(ps):
        end = (d(ps) + timedelta(days=PERIOD_LEN - 1)).isoformat()
        return f"{short(ps)} – {short(end)}, {d(end).year}"

    order = {k: i for i, (k, _) in enumerate(STAGES)}

    # projects
    for p in projects:
        if p["id"] not in files:
            continue
        k = key(p)
        u, b = used.get(k, 0), num(p.get("budget"))
        mine = sorted([x for x in dels if x.get("projectId") == p["id"]], key=lambda x: order.get(x.get("status"), 0))
        done = sum(1 for x in mine if x.get("status") == "done")
        lines = [f"network:: {p.get('network', '')}", f"activity:: {p.get('activity', '')}",
                 f"budget-hours:: {r2(b) if b else '—'}", f"used-hours:: {r2(u)}",
                 f"remaining-hours:: {r2(b - u) if b else '—'}", f"deliverables:: {done}/{len(mine)} done", "",
                 "### Deliverables"]
        for x in mine:
            st = x.get("status", "todo")
            extra = f" · {STAGE_LABEL[st]}" if st in ("doing", "blocked") else ""
            due = f" 📅 {x['due']}" if x.get("due") else ""
            lines.append(f"- [{'x' if st == 'done' else ' '}] {x.get('title', '').strip()}{extra}{due} ^dl-{x['id']}")
        if not mine:
            lines.append("_None yet. Add them on the Board, or type `- [ ] something` here._")
        lines += ["", "### Hours by pay period"]
        pp = per_period.get(k, {})
        if pp:
            lines += ["| Pay period | RG hours |", "| --- | ---: |"]
            lines += [f"| [[{ts_name(ps)}\\|{period_title(ps)}]] | {r2(h)} |" for ps, h in sorted(pp.items(), reverse=True)]
        else:
            lines.append("_No hours charged yet._")
        written += write_region(files[p["id"]], "\n".join(lines))
        man["projects"][p["id"]] = files[p["id"]].relative_to(root).as_posix()

    # timesheets (only periods with hours)
    for ps, per in periods.items():
        tot = period_total(per)
        if not tot:
            continue
        lines = [f"period:: {period_title(ps)}", f"total-hours:: {r2(tot)}", f"target-hours:: {r2(num(s.get('periodHours', 80)))}"]
        for wi, w in enumerate(per.get("weeks", [])):
            ws = d(ps) + timedelta(days=wi * 7)
            days = [ws + timedelta(days=i) for i in range(DAYS)]
            rows = [r for r in w.get("rows", []) if row_total(r)]
            lines += ["", f"### Week {wi + 1} · {short(ws.isoformat())} – {short(days[-1].isoformat())}"]
            if not rows:
                lines.append("_No hours._")
                continue
            lines.append("| Project | Network | Activity | Code | TS | " + " | ".join(f"{x.strftime('%a')} {x.day}" for x in days) + " | Total |")
            lines.append("| --- | --- | --- | --- | --- | " + " | ".join("---:" for _ in days) + " | ---: |")
            for r in rows:
                p = by_key.get(key(r))
                code = r.get("code", "RG")
                name = f"[[{link[p['id']]}]]" if p and p["id"] in link else {"LA": "Annual leave", "LS": "Sick leave", "LH": "Holiday"}.get(code, "")
                hrs = [r2(num(v)) if num(v) else "" for v in r.get("h", [])]
                lines.append(f"| {name} | {cell(r.get('network', ''))} | {cell(r.get('activity', ''))} | {code} | {'TS' if r.get('ts') else ''} | "
                             + " | ".join(hrs) + f" | **{r2(row_total(r))}** |")
            daytot = [sum(num(r.get("h", [""] * DAYS)[i]) for r in rows) for i in range(DAYS)]
            lines.append("| **Total** | | | | | " + " | ".join(r2(x) if x else "" for x in daytot) + f" | **{r2(sum(daytot))}** |")
        written += write_region(folder / "Timesheets" / f"{ts_name(ps)}.md", "\n".join(lines), tail="")

    # leave
    cur = current_start(s)
    lines = []
    for typ, label in (("sick", "Sick leave"), ("annual", "Annual leave")):
        i = leave_info(s, periods, typ, cur)
        lines.append(f"{typ}-balance:: {r2(i['balance']) if i else '—'}")
    last = max([cur] + list(periods.keys()))
    lines += ["", "| Pay period | Sick used | Sick balance | Annual used | Annual balance |", "| --- | ---: | ---: | ---: | ---: |"]
    ps, rows = s["leaveStart"], []
    while ps <= last and len(rows) < 200:
        si, ai = leave_info(s, periods, "sick", ps), leave_info(s, periods, "annual", ps)
        title = period_title(ps) + (" (now)" if ps == cur else "")
        if ps in periods and period_total(periods[ps]):
            title = f"[[{ts_name(ps)}\\|{title}]]"
        rows.append(f"| {title} | {r2(si['used']) if si['used'] else ''} | {r2(si['balance'])} | {r2(ai['used']) if ai['used'] else ''} | {r2(ai['balance'])} |")
        ps = (d(ps) + timedelta(days=PERIOD_LEN)).isoformat()
    lines += list(reversed(rows))
    written += write_region(folder / "Leave balances.md", "\n".join(lines))

    # deliverables board
    lines = []
    for k, label in STAGES:
        items = [x for x in dels if x.get("status") == k]
        lines += [f"### {label} ({len(items)})"]
        for x in items:
            pl = f" — [[{link[x['projectId']]}]]" if x.get("projectId") in link else ""
            due = f" · 📅 {x['due']}" if x.get("due") else ""
            lines.append(f"- {x.get('title', '').strip()}{pl}{due}")
        if not items:
            lines.append("_Nothing here._")
        lines.append("")
    written += write_region(folder / "Deliverables board.md", "\n".join(lines))

    # follow-ups (emails to answer)
    fus = data.get("followups", [])
    lines = []
    for status, label in (("open", "To reply"), ("waiting", "Waiting on them"), ("done", "Done")):
        items = sorted([f for f in fus if f.get("status", "open") == status], key=lambda f: f.get("due") or "9999")
        if status == "done":
            items = items[-20:]
        lines.append(f"### {label} ({len(items)})")
        for f in items:
            who = f" — {f['from']}" if f.get("from") else ""
            pl = f" · [[{link[f['projectId']]}]]" if f.get("projectId") in link else ""
            due = f" · 📅 {f['due']}" if f.get("due") else ""
            lines.append(f"- {'✓ ' if status == 'done' else ''}{cell(f.get('subject') or '(no subject)')}{who}{pl}{due}")
        if not items:
            lines.append("_Nothing here._")
        lines.append("")
    written += write_region(folder / "Follow-ups.md", "\n".join(lines))

    # home
    lines = ["[[Deliverables board]] · [[Leave balances]]", "", "### Projects", "| Project | Network | Activity | Remaining h | Deliverables |",
             "| --- | --- | --- | ---: | --- |"]
    for p in projects:
        if p["id"] not in link:
            continue
        b, u = num(p.get("budget")), used.get(key(p), 0)
        mine = [x for x in dels if x.get("projectId") == p["id"]]
        lines.append(f"| [[{link[p['id']]}]] | {cell(p.get('network', ''))} | {cell(p.get('activity', ''))} | {r2(b - u) if b else '—'} | "
                     f"{sum(1 for x in mine if x.get('status') == 'done')}/{len(mine)} |")
    recent = [ps for ps in sorted(periods, reverse=True) if period_total(periods[ps])][:6]
    lines += ["", "### Recent timesheets"] + ([f"- [[{ts_name(ps)}\\|{period_title(ps)}]] · {r2(period_total(periods[ps]))} h" for ps in recent] or ["_None yet._"])
    written += write_region(folder / f"{folder.name}.md", "\n".join(lines))  # home note, named after the folder

    man["ticks"] = {x["id"]: x.get("status") == "done" for x in dels}
    return written


def cycle(data, manifest_path):
    """Sync ticks from the vault into `data`, then export. Returns (changes, info)."""
    s = data.get("settings", {})
    if not s.get("vaultPath"):
        return 0, None
    info = {"path": s["vaultPath"], "at": time.strftime("%H:%M:%S"), "written": 0, "error": None, "projectFiles": {}}
    try:
        root, folder = target(data)
        if not root.is_dir():
            raise OSError(f"Vault folder not found: {root}")
        man = load_manifest(manifest_path, folder)
        changes = sync(data, man, root)
        info["written"] = export(data, man, root, folder)
        manifest_path.parent.mkdir(exist_ok=True)
        manifest_path.write_text(json.dumps(man, indent=2), encoding="utf-8")
        info["projectFiles"] = man["projects"]
        info["synced"] = changes
        return changes, info
    except (OSError, KeyError, ValueError) as e:
        info["error"] = str(e)
        return 0, info
